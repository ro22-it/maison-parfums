/*
  База ароматов Maison Parfums.
  Факты (бренд, год, ноты, концентрация) — общедоступные данные; описания написаны для этого сайта.
  Фото подгружаются с CDN Fragrantica по номеру аромата (img).

  Формат P(...):
  slug, название, бренд, год, концентрация, пол (m/f/u), номер фото,
  описание в 1 строку, подробное описание,
  ноты "верх|сердце|база", аккорды "имя:процент,...",
  сезоны (w зима, s весна, u лето, a осень), время (d день, n вечер),
  поводы (e каждый день, w работа, s учёба, d свидание, p вечеринка, o особый случай, g подарок),
  стойкость 1–5, шлейф 1–5, тип аромата, объёмы "мл,мл", совет (необязательно)
*/
const PERFUMES = [];
function P(id, name, brand, year, conc, gender, img, short, desc, notes, accords, seasons, times, occ, lon, sil, family, vols, tip) {
  const [top, mid, base] = notes.split('|').map(s => s.split(',').map(n => n.trim()).filter(Boolean));
  PERFUMES.push({
    id, name, brand, year, conc, gender, img, short, desc,
    notes: { top, mid, base },
    accords: accords.split(',').map(a => { const [n, v] = a.split(':'); return { name: n.trim(), value: +v }; }),
    seasons: seasons.split(''), times: times.split(''), occ: occ.split(''),
    lon, sil, family, vols: vols.split(',').map(Number), tip: tip || ''
  });
}

