// Ищем описание: сначала точное совпадение, затем самую длинную известную ноту целыми словами
// («Калабрийский бергамот» → «Бергамот»)
const noteKey = s => s.toLowerCase().replace(/ё/g, 'е').trim();
function noteInfo(name) {
  const k = noteKey(name);
  if (NOTE_INFO[k]) return NOTE_INFO[k];
  const words = ` ${k.replace(/[^a-zа-я0-9 -]/g, ' ')} `;
  let best = null;
  for (const key in NOTE_INFO) if (words.includes(` ${key} `) && (!best || key.length > best.length)) best = key;
  return best ? NOTE_INFO[best] : null;
}

/* ---------- Панель «что это за нота» ---------- */
const notePerfumes = name => { const k = noteKey(name); return PERFUMES.filter(p => [...p.notes.top, ...p.notes.mid, ...p.notes.base].some(x => noteKey(x).includes(k))); };

function openNote(name) {
  let ov = document.getElementById('noteOv');
  if (!ov) {
    ov = document.createElement('div');
    ov.className = 'note-ov'; ov.id = 'noteOv';
    ov.innerHTML = `<aside class="note-dw" role="dialog" aria-modal="true" aria-label="Нота"><button class="note-dw__x" type="button">Закрыть ×</button><div class="note-dw__body"></div></aside>`;
    document.body.appendChild(ov);
    ov.addEventListener('click', e => { if (e.target === ov || e.target.closest('.note-dw__x')) closeNote(); });
  }
  const info = noteInfo(name), list = notePerfumes(name);
  ov.querySelector('.note-dw__body').innerHTML = `
    <div class="note-dw__kicker">Нота</div>
    <h2 class="note-dw__title">${esc(name)}</h2>
    ${info ? `<span class="note-dw__fam">${esc(info[0])}</span>` : ''}
    <div class="note-dw__art" aria-hidden="true"><b>${esc(name[0])}</b></div>
    <div class="note-dw__label">Как пахнет</div>
    <p class="note-dw__text">${info ? esc(info[1]) : 'Описание этой ноты пока не добавлено.'}</p>
    <div class="note-dw__count">Встречается в ${list.length} ${plural(list.length, 'аромате', 'ароматах', 'ароматах')} из ${PERFUMES.length}</div>
    ${list.length ? `<div class="note-dw__label">Например</div>
    <div class="note-dw__list">${list.slice(0, 4).map(p => `<a href="perfume.html?id=${p.id}" data-link><span>${esc(p.name)}</span><small>${esc(p.brand)}</small></a>`).join('')}</div>` : ''}
    <button class="btn note-dw__go" type="button" data-note-search="${esc(name)}">Все ароматы с этой нотой</button>`;
  ov.querySelector('.note-dw').scrollTop = 0;
  requestAnimationFrame(() => ov.classList.add('on'));
}
function closeNote() { document.getElementById('noteOv')?.classList.remove('on'); }

document.addEventListener('click', e => {
  const go = e.target.closest('[data-note-search]');
  if (go) {
    const n = go.dataset.noteSearch;
    closeNote();
    // на главной фильтр ставится сразу, с других страниц — через sessionStorage
    if (typeof window.searchByNote === 'function') return window.searchByNote(n);
    try { sessionStorage.setItem('mp_note', n); } catch {}
    location.href = 'index.html#catalog';
    return;
  }
  const t = e.target.closest('[data-note-info]');
  if (t && !e.target.closest('[data-rm]')) openNote(t.dataset.noteInfo);
});
document.addEventListener('keydown', e => {
  if (e.key === 'Escape') closeNote();
  const t = e.target.closest?.('[data-note-info]');
  if (t && e.key === 'Enter') openNote(t.dataset.noteInfo);
});
